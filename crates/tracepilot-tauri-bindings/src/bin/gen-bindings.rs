#![cfg_attr(test, allow(clippy::unwrap_used, clippy::expect_used))]
//! Phase 1B.1 pilot: thin shim over [`tracepilot_tauri_bindings::specta_exports::export`].
//!
//! Run via `pnpm gen:bindings` (or
//! `cargo run -p tracepilot-tauri-bindings --bin gen-bindings` from the
//! repo root). Emits:
//!
//!   - `packages/client/src/generated/bindings.ts` — the specta-typed
//!     TypeScript client for the pilot allow-list (types + invoke wrappers).
//!   - `packages/client/src/generated/ipc-commands.ts` — the client's
//!     `IPC_COMMANDS` const (re-exported by `packages/client/src/commands.ts`).
//!   - `packages/client/src/generated/ipc-commands.json` — the same list as
//!     JSON for tests and tools that cannot import TypeScript.
//!
//!   Both are sorted copies of `IPC_COMMAND_NAMES`, the Rust source of truth
//!   at `crates/tracepilot-tauri-bindings/src/ipc_command_names.rs`.
//!
//! The heavy lifting for the `bindings.ts` side lives inside the lib crate so
//! that the hidden per-command macros generated by `#[specta::specta]` (which
//! are only reachable from within the defining crate) can be resolved by
//! `collect_commands!`.

use std::path::PathBuf;

use tracepilot_tauri_bindings::IPC_COMMAND_NAMES;

// This developer command reports the generated artifact paths on stdout.
#[allow(clippy::print_stdout)]
fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Resolve output paths relative to the crate manifest so `cargo run` from
    // the repo root, a crate dir, or an IDE all work identically.
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let generated_dir = manifest_dir
        .join("..")
        .join("..")
        .join("packages")
        .join("client")
        .join("src")
        .join("generated");

    std::fs::create_dir_all(&generated_dir)?;

    let bindings_path = generated_dir.join("bindings.ts");
    tracepilot_tauri_bindings::specta_exports::export(&bindings_path)?;
    println!("wrote {}", bindings_path.display());

    let names = sorted_command_names();
    let manifest_path = generated_dir.join("ipc-commands.json");
    std::fs::write(&manifest_path, ipc_command_manifest(&names))?;
    println!("wrote {}", manifest_path.display());

    let ts_path = generated_dir.join("ipc-commands.ts");
    std::fs::write(&ts_path, ipc_command_module(&names))?;
    println!("wrote {}", ts_path.display());

    let contracts_path = generated_dir.join("../../../types/src/generated/contracts.ts");
    tracepilot_tauri_bindings::specta_exports::export_contracts(&contracts_path)?;
    println!("wrote {}", contracts_path.display());

    Ok(())
}

/// The IPC command list, sorted so the generated files stay stable when
/// entries move between groups in the Rust source.
fn sorted_command_names() -> Vec<&'static str> {
    let mut names: Vec<&str> = IPC_COMMAND_NAMES.to_vec();
    names.sort_unstable();
    names.dedup();
    assert_eq!(
        names.len(),
        IPC_COMMAND_NAMES.len(),
        "IPC_COMMAND_NAMES contains duplicate entries"
    );
    names
}

/// The names as a JSON array, serialised by hand so the output is stable and
/// trivially diffable.
fn ipc_command_manifest(names: &[&str]) -> String {
    let entries: Vec<String> = names.iter().map(|name| format!("  \"{name}\"")).collect();
    format!("[\n{}\n]\n", entries.join(",\n"))
}

/// The names as the client's `IPC_COMMANDS` const.
fn ipc_command_module(names: &[&str]) -> String {
    let mut body = String::from(
        "// DO NOT EDIT — generated by `pnpm gen:bindings` from\n\
         // crates/tracepilot-tauri-bindings/src/ipc_command_names.rs.\n\
         // On a merge conflict, take either side and re-run `pnpm gen:bindings`.\n\
         \n\
         /** Every Tauri IPC command the desktop backend registers. */\n\
         export const IPC_COMMANDS = [\n",
    );
    for name in names {
        body.push_str("  \"");
        body.push_str(name);
        body.push_str("\",\n");
    }
    body.push_str("] as const;\n");
    body
}
