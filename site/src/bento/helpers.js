export function sparkPath(vals, w, h, pad) {
  pad = pad || 2;
  const max = Math.max.apply(null, vals) || 1,
    min = Math.min.apply(null, vals);
  const n = vals.length;
  return vals
    .map(
      (v, i) =>
        (i ? "L" : "M") +
        (pad + (i * (w - pad * 2)) / (n - 1)).toFixed(1) +
        " " +
        (h - pad - ((v - min) / (max - min || 1)) * (h - pad * 2)).toFixed(1),
    )
    .join(" ");
}
export function smoothPath(vals, w, h, pad) {
  const max = Math.max.apply(null, vals) || 1,
    min = Math.min.apply(null, vals) * 0.85;
  const n = vals.length;
  const pts = vals.map((v, i) => [
    3 + (i * (w - 6)) / (n - 1),
    h - pad - ((v - min) / (max - min || 1)) * (h - pad * 2),
  ]);
  let d = `M${pts[0][0].toFixed(1)} ${pts[0][1].toFixed(1)}`;
  for (let i = 0; i < n - 1; i++) {
    const p0 = pts[i - 1] || pts[i],
      p1 = pts[i],
      p2 = pts[i + 1],
      p3 = pts[i + 2] || p2;
    d +=
      " C" +
      (p1[0] + (p2[0] - p0[0]) / 6).toFixed(1) +
      " " +
      (p1[1] + (p2[1] - p0[1]) / 6).toFixed(1) +
      " " +
      (p2[0] - (p3[0] - p1[0]) / 6).toFixed(1) +
      " " +
      (p2[1] - (p3[1] - p1[1]) / 6).toFixed(1) +
      " " +
      p2[0].toFixed(1) +
      " " +
      p2[1].toFixed(1);
  }
  return d;
}
